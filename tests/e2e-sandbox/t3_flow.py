import asyncio,json,datetime
from lib import *
RES=[]
def chk(name,cond,extra=''):
    RES.append((name,bool(cond),extra)); print(('PASS' if cond else 'FAIL'),'::',name,extra if not cond else '')
async def fsdoc(pg,path): return await pg.evaluate("p=>JSON.parse(localStorage.getItem('__FS'))[p]",path)
async def fsall(pg,prefix): return await pg.evaluate("p=>{const s=JSON.parse(localStorage.getItem('__FS'));return Object.keys(s).filter(k=>k.startsWith(p)).map(k=>[k,s[k]])}",prefix)
async def toast(pg): return await pg.evaluate("()=>[...document.querySelectorAll('.toast,#toast,[class*=toast]')].map(e=>e.textContent.trim()).filter(Boolean).join('|')")
async def modal_open(pg): return await pg.evaluate("()=>!!document.getElementById('activeModal')")
async def main():
    S=Session(); pg=await S.start(seed=seed_script(),logged_in=True)
    await pg.goto(BASE+'dashboard.html'); await pg.wait_for_timeout(1200)
    # A. add customer validations
    await pg.evaluate("openAddCustomer()"); await pg.wait_for_timeout(400)
    await pg.click('#activeModal :is(.modal-actions,.txn-actions) > button:last-child'); await pg.wait_for_timeout(300)
    chk('empty name rejected (modal stays)',await modal_open(pg))
    await pg.fill('#mName','Ramesh Kumar'); await pg.fill('#mEmail','bad-email')
    await pg.click('#activeModal :is(.modal-actions,.txn-actions) > button:last-child'); await pg.wait_for_timeout(300)
    chk('bad email rejected',await modal_open(pg))
    await pg.fill('#mEmail',''); await pg.fill('#mPhone','98765-00001abc')
    chk('phone input digits limited',len(await pg.input_value('#mPhone'))<=10)
    await pg.click('#activeModal :is(.modal-actions,.txn-actions) > button:last-child'); await pg.wait_for_timeout(700)
    chk('modal closed after save',not await modal_open(pg))
    parties=await fsall(pg,'users/u_test/parties/')
    chk('party stored',len(parties)==1,str(parties))
    pid=parties[0][0].split('/')[-1]; party=parties[0][1]
    chk('party phone digits only',party['phone'].isdigit(),party['phone'])
    pv=await fsall(pg,'publicViews/')
    chk('public view created w/ token',len(pv)==1 and pv[0][0].endswith(party['viewToken']))
    chk('card shown on dashboard',await pg.locator('.customer-card').count()==1)
    # search
    await pg.fill('input[placeholder*="ग्राहक खोजें"]','zzz'); await pg.wait_for_timeout(300)
    chk('search no match -> 0 cards',await pg.locator('.customer-card').count()==0)
    await pg.fill('input[placeholder*="ग्राहक खोजें"]','rames'); await pg.wait_for_timeout(300)
    chk('search match -> 1 card',await pg.locator('.customer-card').count()==1)
    await pg.fill('input[placeholder*="ग्राहक खोजें"]',''); await pg.wait_for_timeout(300)
    await pg.click('.customer-card'); await pg.wait_for_timeout(500)
    chk('customer screen active',await pg.evaluate("()=>document.getElementById('screen-customer').classList.contains('active')"))
    # B. udhaar & jama
    await pg.click('button.action-btn.udhaar'); await pg.wait_for_timeout(400)
    await pg.fill('#mAmt','0'); await pg.click('#activeModal :is(.modal-actions,.txn-actions) > button:last-child'); await pg.wait_for_timeout(200)
    chk('zero amount rejected',await modal_open(pg))
    await pg.fill('#mAmt','1000'); await pg.fill('#mNote','चावल'); await pg.click('#activeModal :is(.modal-actions,.txn-actions) > button:last-child'); await pg.wait_for_timeout(900)
    chk('udhaar saved, modal closed',not await modal_open(pg))
    chk('balance=1000',(await fsdoc(pg,f'users/u_test/parties/{pid}'))['balance']==1000)
    await pg.click('button.action-btn.jama'); await pg.wait_for_timeout(400)
    await pg.fill('#mAmt','400'); await pg.click('#activeModal :is(.modal-actions,.txn-actions) > button:last-child'); await pg.wait_for_timeout(900)
    chk('balance=600',(await fsdoc(pg,f'users/u_test/parties/{pid}'))['balance']==600)
    pvd=(await fsall(pg,'publicViews/'))[0][1]
    chk('public view balance=600',pvd['balance']==600,str(pvd.get('balance')))
    await pg.screenshot(path='s_cust.png')
    # C. loan
    d0=(datetime.date.today()-datetime.timedelta(days=65)).isoformat()
    await pg.click('button.more-btn'); await pg.wait_for_timeout(300)
    await pg.click('.more-row:has-text("लोन / ब्याज")'); await pg.wait_for_timeout(500)
