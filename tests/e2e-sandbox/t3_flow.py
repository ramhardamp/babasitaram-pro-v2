    await pg.click('#activeModal :is(.modal-actions,.txn-actions) > button:last-child'); await pg.wait_for_timeout(1000)
    txs=await fsall(pg,'users/u_test/transactions/')
    loans=[t for k,t in txs if t['type']=='byaj_loan']
    chk('loan txn stored',len(loans)==1,str(loans))
    chk('loan card visible',await pg.locator('.loan-card').count()==1)
    txt=await pg.evaluate("()=>document.querySelector('.loan-card').innerText")
    print('   loan card:',txt.replace('\n',' | '))
    await pg.screenshot(path='s_loan.png')
    # repay
    await pg.click('button.more-btn'); await pg.click('.more-row:has-text("लोन वापसी")'); await pg.wait_for_timeout(500)
    await pg.fill('#mRepay','2000'); await pg.click('#activeModal :is(.modal-actions,.txn-actions) > button:last-child'); await pg.wait_for_timeout(1000)
    txs=await fsall(pg,'users/u_test/transactions/')
    chk('repay txn stored',any(t['type']=='loan_repay' and t['amount']==2000 for k,t in txs))
    await pg.click('button.more-btn'); await pg.click('.more-row:has-text("ब्याज भुगतान")'); await pg.wait_for_timeout(500)
    await pg.fill('#mIntAmt','100'); await pg.click('#activeModal :is(.modal-actions,.txn-actions) > button:last-child'); await pg.wait_for_timeout(1000)
    txs=await fsall(pg,'users/u_test/transactions/')
    chk('interest paid stored',any(t['type']=='interest_paid' and t['amount']==100 for k,t in txs))
    # repay more than principal?
    await pg.click('button.more-btn'); await pg.click('.more-row:has-text("लोन वापसी")'); await pg.wait_for_timeout(500)
    await pg.fill('#mRepay','999999'); await pg.click('#activeModal :is(.modal-actions,.txn-actions) > button:last-child'); await pg.wait_for_timeout(800)
    txs=await fsall(pg,'users/u_test/transactions/')
    over=[t for k,t in txs if t['type']=='loan_repay' and t['amount']==999999]
